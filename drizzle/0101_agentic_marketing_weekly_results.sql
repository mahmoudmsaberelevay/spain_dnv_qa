-- ELEVAY Agentic Marketing System: Setup and Weekly Results control plane.
-- This migration stores internal planning, individual decisions, feedback memory, and aggregate performance only.
-- It does not create any provider dispatch, media generation, publication, Meta/CAPI, campaign, spend, or CRM operating-data path.

CREATE TABLE IF NOT EXISTS `marketing_weekly_results_settings` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `settingsKey` VARCHAR(96) NOT NULL,
  `timezone` VARCHAR(64) NOT NULL DEFAULT 'Africa/Cairo',
  `prepareDayOfWeek` INT NOT NULL DEFAULT 6,
  `prepareStartTime` VARCHAR(5) NOT NULL DEFAULT '08:00',
  `deliveryDeadlineTime` VARCHAR(5) NOT NULL DEFAULT '10:00',
  `preparationScheduleEnabled` TINYINT(1) NOT NULL DEFAULT 1,
  `scheduleState` VARCHAR(48) NOT NULL DEFAULT 'waiting_execution_release',
  `weeklyGoal` MEDIUMTEXT NULL,
  `programPrioritiesJson` MEDIUMTEXT NOT NULL,
  `updatedSourcesNote` MEDIUMTEXT NULL,
  `creativeDirection` MEDIUMTEXT NULL,
  `contentMixJson` MEDIUMTEXT NOT NULL,
  `allocationRulesJson` MEDIUMTEXT NOT NULL,
  `learningEnabled` TINYINT(1) NOT NULL DEFAULT 1,
  `lastScheduleAttemptAt` BIGINT NULL,
  `lastScheduleStatus` VARCHAR(48) NULL,
  `lastChangedByUserId` INT NOT NULL,
  `createdAt` BIGINT NOT NULL,
  `updatedAt` BIGINT NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `marketing_weekly_results_settings_key_unique` (`settingsKey`),
  KEY `marketing_weekly_results_settings_state_idx` (`scheduleState`, `updatedAt`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `marketing_weekly_results_plans` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `planKey` VARCHAR(96) NOT NULL,
  `periodStart` VARCHAR(10) NOT NULL,
  `version` INT NOT NULL,
  `status` VARCHAR(48) NOT NULL DEFAULT 'draft_prepared',
  `source` VARCHAR(48) NOT NULL DEFAULT 'manual_internal',
  `title` VARCHAR(300) NOT NULL,
  `weeklyGoal` MEDIUMTEXT NULL,
  `creativeDirection` MEDIUMTEXT NULL,
  `setupSnapshotJson` MEDIUMTEXT NOT NULL,
  `previousWeekPerformanceJson` MEDIUMTEXT NOT NULL,
  `preferenceMemoryJson` MEDIUMTEXT NOT NULL,
  `planHash` VARCHAR(64) NOT NULL,
  `preparedByUserId` INT NULL,
  `preparedAt` BIGINT NOT NULL,
  `deliveryDeadlineAt` BIGINT NULL,
  `createdAt` BIGINT NOT NULL,
  `updatedAt` BIGINT NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `marketing_weekly_results_plan_key_unique` (`planKey`),
  UNIQUE KEY `marketing_weekly_results_period_version_unique` (`periodStart`, `version`),
  KEY `marketing_weekly_results_plan_period_idx` (`periodStart`, `status`),
  KEY `marketing_weekly_results_plan_updated_idx` (`updatedAt`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `marketing_weekly_results_items` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `planId` INT NOT NULL,
  `position` INT NOT NULL,
  `itemType` VARCHAR(48) NOT NULL,
  `title` VARCHAR(300) NOT NULL,
  `programKey` VARCHAR(96) NULL,
  `objective` VARCHAR(500) NOT NULL,
  `creativeDirection` MEDIUMTEXT NULL,
  `scriptCopy` MEDIUMTEXT NULL,
  `caption` MEDIUMTEXT NULL,
  `cta` VARCHAR(500) NULL,
  `hashtagsJson` MEDIUMTEXT NOT NULL,
  `visualBrief` MEDIUMTEXT NULL,
  `plannedDay` VARCHAR(16) NULL,
  `plannedTime` VARCHAR(5) NULL,
  `previewUrl` VARCHAR(2000) NULL,
  `previewHash` VARCHAR(64) NULL,
  `sourceClaimIdsJson` MEDIUMTEXT NOT NULL,
  `metadataJson` MEDIUMTEXT NOT NULL,
  `isSelected` TINYINT(1) NOT NULL DEFAULT 1,
  `requiresIndividualApproval` TINYINT(1) NOT NULL DEFAULT 1,
  `status` VARCHAR(48) NOT NULL DEFAULT 'draft',
  `blockedReason` MEDIUMTEXT NULL,
  `contentPacketId` INT NULL,
  `approvedByUserId` INT NULL,
  `approvedAt` BIGINT NULL,
  `stoppedByUserId` INT NULL,
  `stoppedAt` BIGINT NULL,
  `createdByUserId` INT NOT NULL,
  `lastEditedByUserId` INT NOT NULL,
  `createdAt` BIGINT NOT NULL,
  `updatedAt` BIGINT NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `marketing_weekly_results_item_plan_position_unique` (`planId`, `position`),
  KEY `marketing_weekly_results_item_plan_status_idx` (`planId`, `status`, `position`),
  KEY `marketing_weekly_results_item_selected_idx` (`planId`, `isSelected`, `status`),
  KEY `marketing_weekly_results_item_program_idx` (`programKey`, `updatedAt`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `marketing_weekly_results_item_events` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `itemId` INT NOT NULL,
  `action` VARCHAR(64) NOT NULL,
  `fromStatus` VARCHAR(48) NULL,
  `toStatus` VARCHAR(48) NULL,
  `feedback` MEDIUMTEXT NULL,
  `changedFieldsJson` MEDIUMTEXT NOT NULL,
  `payloadJson` MEDIUMTEXT NOT NULL,
  `actorUserId` INT NOT NULL,
  `createdAt` BIGINT NOT NULL,
  PRIMARY KEY (`id`),
  KEY `marketing_weekly_results_item_event_item_idx` (`itemId`, `createdAt`),
  KEY `marketing_weekly_results_item_event_action_idx` (`action`, `createdAt`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `marketing_weekly_results_preference_memories` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `scope` VARCHAR(48) NOT NULL DEFAULT 'weekly_results',
  `scopeKey` VARCHAR(96) NULL,
  `preferenceText` MEDIUMTEXT NOT NULL,
  `sourceItemId` INT NULL,
  `sourceEventId` INT NULL,
  `status` VARCHAR(32) NOT NULL DEFAULT 'active',
  `createdByUserId` INT NOT NULL,
  `createdAt` BIGINT NOT NULL,
  `updatedAt` BIGINT NOT NULL,
  PRIMARY KEY (`id`),
  KEY `marketing_weekly_results_preference_status_idx` (`status`, `updatedAt`),
  KEY `marketing_weekly_results_preference_scope_idx` (`scope`, `scopeKey`, `updatedAt`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `marketing_weekly_results_performance_snapshots` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `periodStart` VARCHAR(10) NOT NULL,
  `source` VARCHAR(48) NOT NULL DEFAULT 'manual_aggregate',
  `spendEgp` DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  `impressions` BIGINT NOT NULL DEFAULT 0,
  `clicks` BIGINT NOT NULL DEFAULT 0,
  `leadForms` BIGINT NOT NULL DEFAULT 0,
  `qualifiedLeads` BIGINT NOT NULL DEFAULT 0,
  `clientStageLeads` BIGINT NOT NULL DEFAULT 0,
  `notes` MEDIUMTEXT NULL,
  `recordedByUserId` INT NOT NULL,
  `recordedAt` BIGINT NOT NULL,
  `updatedAt` BIGINT NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `marketing_weekly_results_performance_period_source_unique` (`periodStart`, `source`),
  KEY `marketing_weekly_results_performance_period_idx` (`periodStart`, `recordedAt`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

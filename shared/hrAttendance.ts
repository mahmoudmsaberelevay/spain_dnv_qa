import { ELEVAY_TIME_ZONE, getCairoBusinessDate } from "./financialEmployeeSalaryRates";

export type HrAttendanceRecord = {
  id: number;
  attendanceDate: string | Date;
  checkInAt: Date;
  checkOutAt: Date | null;
};

export function toHrAttendanceDate(value: string | Date): string {
  if (typeof value === "string") return value.slice(0, 10);
  return value.toISOString().slice(0, 10);
}

export function assertHrAttendanceDate(value: string): string {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) {
    throw new Error("Attendance dates must use YYYY-MM-DD");
  }
  const parsed = new Date(`${value}T00:00:00.000Z`);
  if (Number.isNaN(parsed.getTime()) || parsed.toISOString().slice(0, 10) !== value) {
    throw new Error("Attendance dates must be valid calendar days");
  }
  return value;
}

export function resolveHrAttendanceRange(from?: string, to?: string): { from?: string; to?: string } {
  const normalizedFrom = from ? assertHrAttendanceDate(from) : undefined;
  const normalizedTo = to ? assertHrAttendanceDate(to) : undefined;
  if (normalizedFrom && normalizedTo && normalizedFrom > normalizedTo) {
    throw new Error("Attendance report start date must be on or before the end date");
  }
  return { from: normalizedFrom, to: normalizedTo };
}

export function getCairoMonthBounds(date: Date = new Date()): { from: string; to: string } {
  const [yearText, monthText] = getCairoBusinessDate(date).split("-");
  const year = Number(yearText);
  const month = Number(monthText);
  const lastDay = new Date(Date.UTC(year, month, 0)).getUTCDate();
  return {
    from: `${yearText}-${monthText}-01`,
    to: `${yearText}-${monthText}-${String(lastDay).padStart(2, "0")}`,
  };
}

/**
 * Attendance timestamps are generated by the server. The duration is therefore
 * an auditable elapsed-time display, never a browser-supplied work-hours value.
 */
export function getAttendanceDurationMinutes(record: Pick<HrAttendanceRecord, "checkInAt" | "checkOutAt">, now: Date = new Date()): number {
  const start = new Date(record.checkInAt).getTime();
  const end = new Date(record.checkOutAt ?? now).getTime();
  if (!Number.isFinite(start) || !Number.isFinite(end) || end <= start) return 0;
  return Math.floor((end - start) / 60_000);
}

export function formatAttendanceDuration(minutes: number): string {
  const safeMinutes = Math.max(0, Math.floor(minutes || 0));
  const hours = Math.floor(safeMinutes / 60);
  const remainder = safeMinutes % 60;
  return `${hours}h ${remainder}m`;
}

export function formatCairoAttendanceTime(value: Date | string | null | undefined): string {
  if (!value) return "—";
  return new Intl.DateTimeFormat("en-GB", {
    timeZone: ELEVAY_TIME_ZONE,
    hour: "2-digit",
    minute: "2-digit",
    hour12: true,
  }).format(new Date(value));
}
